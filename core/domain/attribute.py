from dataclasses import dataclass
from datetime import datetime

from core.enum.attribute_type import AttributeType


@dataclass
class Attribute:
    """
    Domain object representing a patent or analog attribute.

    An attribute is a characteristic or property that can be associated with
    patents, analogs, or used for identification matching.

    Attributes are immutable in terms of their core properties (name, type)
    but can be updated in the database through the repository layer.

    Attributes:
        name: The attribute name/title (required, non-empty, max 1000 chars)
        id: Unique identifier (auto-generated by database, optional for new objects)
        type: Attribute classification (PATENT, ANALOG, COMBINED, IDENTIFIER, MATCHING_ANALOG)
        created_at: Timestamp when attribute was created
        updated_at: Timestamp when attribute was last modified
    """

    name: str
    id: int | None = None
    type: AttributeType | None = None
    # None: set by the DB on create, left untouched by BaseService.update.
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self):
        """Validate attribute data after initialization."""
        self._validate_name()
        self._validate_type()

    def _validate_name(self) -> None:
        """
        Validate attribute name.

        Rules:
            - Name cannot be None or empty
            - Name cannot consist only of whitespace
            - Name length cannot exceed 1000 characters

        Raises:
            ValueError: If name validation fails
        """
        if not self.name or not self.name.strip():
            raise ValueError("Attribute name cannot be empty")

        stripped_name = self.name.strip()
        if len(stripped_name) > 1000:
            raise ValueError(f"Attribute name too long: {len(stripped_name)} chars, max 1000")

    def _validate_type(self) -> None:
        """
        Validate attribute type.

        Note: Type can be None for new attributes that haven't been classified yet.
        This is allowed but will be validated before persistence.

        Raises:
            ValueError: If type is invalid (not an AttributeType enum value)
        """
        if self.type is not None and not isinstance(self.type, AttributeType):
            raise ValueError(
                f"Invalid attribute type: {self.type}. Must be AttributeType enum value"
            )

    @classmethod
    def create(
        cls,
        name: str,
        attr_type: AttributeType | None = None,
        attr_id: int | None = None,
    ) -> "Attribute":
        """
        Factory method to create a new Attribute instance.

        This is the preferred way to create Attribute objects as it provides
        a clean interface with automatic validation and defaults.

        Args:
            name: Attribute name/title (required)
            attr_type: Attribute classification type (optional, defaults to None)
            attr_id: Optional existing ID for reconstruction from database

        Returns:
            A new validated Attribute instance

        Raises:
            ValueError: If validation fails (empty name, too long, etc.)

        Examples:
            >>> # Create a new patent attribute
            >>> attr = Attribute.create(
            ...     name="Tensile Strength",
            ...     attr_type=AttributeType.PATENT
            ... )

            >>> # Create an identifier attribute for matching
            >>> identifier = Attribute.create(
            ...     name="Material Composition",
            ...     attr_type=AttributeType.IDENTIFIER
            ... )

            >>> # Reconstruct from database
            >>> existing = Attribute.create(
            ...     name="Weight",
            ...     attr_type=AttributeType.COMBINED
            ... )
        """
        # Validate and clean the name
        if not name or not name.strip():
            raise ValueError("Attribute name cannot be empty")

        cleaned_name = name.strip()

        if len(cleaned_name) > 1000:
            raise ValueError(f"Attribute name too long: {len(cleaned_name)} chars, max 1000")

        # Create instance with validated data
        return cls(name=cleaned_name, id=attr_id, type=attr_type)

    @classmethod
    def create_batch(
        cls, names: list[str], attr_type: AttributeType | None = None
    ) -> list["Attribute"]:
        """
        Factory method to create multiple Attribute instances at once.

        Useful for bulk creation of attributes from lists of names.

        Args:
            names: List of attribute names to create
            attr_type: Attribute type to apply to all created attributes

        Returns:
            List of created Attribute instances

        Raises:
            ValueError: If any name in the list is invalid

        Examples:
            >>> attributes = Attribute.create_batch(
            ...     names=["Width", "Height", "Depth"],
            ...     attr_type=AttributeType.COMBINED
            ... )
        """
        return [cls.create(name=name, attr_type=attr_type) for name in names]

    def update_name(self, new_name: str) -> "Attribute":
        """
        Create a new Attribute instance with updated name.

        Since attributes are conceptually immutable, this creates a new instance
        rather than modifying the existing one.

        Args:
            new_name: New name for the attribute

        Returns:
            New Attribute instance with updated name and updated_at timestamp

        Raises:
            ValueError: If new_name is invalid

        Examples:
            >>> old_attr = Attribute.create("Old Name")
            >>> new_attr = old_attr.update_name("New Name")
            >>> new_attr.name
            'New Name'
        """
        if not new_name or not new_name.strip():
            raise ValueError("New attribute name cannot be empty")

        cleaned_name = new_name.strip()

        if len(cleaned_name) > 1000:
            raise ValueError(f"New attribute name too long: {len(cleaned_name)} chars, max 1000")

        return Attribute(
            name=cleaned_name,
            id=self.id,
            type=self.type,
            created_at=self.created_at,
            updated_at=datetime.now(),
        )

    def change_type(self, new_type: AttributeType) -> "Attribute":
        """
        Create a new Attribute instance with updated type.

        Args:
            new_type: New attribute type

        Returns:
            New Attribute instance with updated type and updated_at timestamp

        Examples:
            >>> attr = Attribute.create("Test", attr_type=AttributeType.PATENT)
            >>> new_attr = attr.change_type(AttributeType.IDENTIFIER)
            >>> new_attr.type
            <AttributeType.IDENTIFIER: 'identifier'>
        """
        if not isinstance(new_type, AttributeType):
            raise ValueError(f"Invalid type: {new_type}. Must be AttributeType enum")

        return Attribute(
            name=self.name,
            id=self.id,
            type=new_type,
            created_at=self.created_at,
            updated_at=datetime.now(),
        )

    def to_dict(self) -> dict:
        """
        Convert attribute to dictionary representation.

        Useful for serialization, logging, or API responses.

        Returns:
            Dictionary with attribute data

        Examples:
            >>> attr = Attribute.create("Test", attr_type=AttributeType.PATENT)
            >>> attr.to_dict()
            {
                'id': None,
                'name': 'Test',
                'type': 'patent',
                'created_at': '2024-01-01T12:00:00',
                'updated_at': '2024-01-01T12:00:00'
            }
        """
        return {
            "id": self.id,
            "name": self.name,
            "type": self.type.value if self.type else None,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "Attribute":
        """
        Create Attribute instance from dictionary representation.

        Useful for deserialization from API responses or database records.

        Args:
            data: Dictionary with attribute data (from to_dict())

        Returns:
            Attribute instance

        Examples:
            >>> data = {'id': 1, 'name': 'Test', 'type': 'patent'}
            >>> attr = Attribute.from_dict(data)
        """
        attr_type = None
        if data.get("type"):
            attr_type = AttributeType(data["type"])

        return cls.create(name=data["name"], attr_type=attr_type, attr_id=data.get("id"))

    def __hash__(self) -> int:
        """
        Make Attribute hashable for use as dictionary key.

        Uses id if available, otherwise falls back to name+type combination.
        This allows attributes to be used in sets and as dict keys.

        Returns:
            Hash value for the attribute

        Examples:
            >>> attr1 = Attribute.create("Test")
            >>> attr2 = Attribute.create("Test")
            >>> len({attr1, attr2})  # Different instances, same name
            1
        """
        if self.id is not None:
            return hash(self.id)
        return hash((self.name, self.type))

    def __eq__(self, other: object) -> bool:
        """
        Compare two Attribute instances for equality.

        Attributes are considered equal if they have the same:
        - ID (if both have IDs), OR
        - Name and type (if IDs are not available)

        Args:
            other: Object to compare with

        Returns:
            True if attributes are equal, False otherwise

        Examples:
            >>> attr1 = Attribute.create("Test", attr_type=AttributeType.PATENT)
            >>> attr2 = Attribute.create("Test", attr_type=AttributeType.PATENT)
            >>> attr1 == attr2
            True
        """
        if not isinstance(other, Attribute):
            return False

        # If both have IDs, compare by ID
        if self.id is not None and other.id is not None:
            return self.id == other.id

        # Otherwise compare by name and type
        return self.name == other.name and self.type == other.type

    def __repr__(self) -> str:
        """
        String representation for debugging.

        Returns:
            Human-readable representation of the attribute
        """
        type_str = self.type.value if self.type else "None"
        id_str = f"id={self.id}, " if self.id else ""
        return f"Attribute({id_str}name='{self.name}', type='{type_str}')"
